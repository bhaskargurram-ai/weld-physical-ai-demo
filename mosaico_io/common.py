def data_dir() -> Path:
    return Path(os.environ.get("DATA_DIR", "data"))


def generated_dir() -> Path:
    return Path(os.environ.get("WELD_GENERATED_DIR", data_dir() / "generated"))


def host_port() -> tuple[str, int]:
    return os.environ.get("MOSAICO_HOST", "localhost"), int(os.environ.get("MOSAICO_PORT", "6726"))


def _env_offline() -> Optional[bool]:
    v = os.environ.get("MOSAICO_OFFLINE")
    if v is None or v == "":
        return None
    return v.strip().lower() in ("1", "true", "yes", "on")


_CLIENT = None
_ONLINE_OK: Optional[bool] = None


def connect(host: Optional[str] = None, port: Optional[int] = None, timeout: int = 5):
    """Return a (cached) ``MosaicoClient`` connected to mosaicod (MOSAICO_HOST/MOSAICO_PORT)."""
    global _CLIENT
    from mosaicolabs import MosaicoClient
    import mosaico_io.ontology  # noqa: F401  (registers WeldArc/WeldTravel/WeldThermal)

    h, p = host_port()
    host, port = host or h, port or p
    if _CLIENT is not None and (host, port) == host_port():
        return _CLIENT
    client = MosaicoClient.connect(host=host, port=port, timeout=timeout)
    if (host, port) == host_port():
        _CLIENT = client
    return client


def is_offline() -> bool:
    """True when reading local files. MOSAICO_OFFLINE=1 forces it; MOSAICO_OFFLINE=0 forces online.
    Unset: try mosaicod once and fall back to offline if it is unreachable."""
    global _ONLINE_OK
    env = _env_offline()
    if env is not None:
        return env
    if _ONLINE_OK is None:
        try:
            connect(timeout=2)
            _ONLINE_OK = True
        except Exception as e:  # pragma: no cover - depends on environment
            log.warning("mosaicod unreachable at %s:%s (%s) -> offline mode", *host_port(), e)
            _ONLINE_OK = False
    return not _ONLINE_OK


def clean_json(o: Any) -> Any:
    """NaN/inf -> None, numpy scalars -> python, recursively (mosaicod metadata is strict JSON)."""
    if isinstance(o, dict):
        return {k: clean_json(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean_json(v) for v in o]
    if isinstance(o, np.generic):
        o = o.item()
    if isinstance(o, float) and not math.isfinite(o):
        return None
    return o


_BAD_KEY = re.compile(r"[^A-Za-z0-9 _-]")


def metadata_safe(o: Any) -> Any:
    """clean_json + keys mosaicod accepts: it rejects '.', '/', ':' ... in (nested) metadata keys,
    e.g. AIMEN's HDF5 config '05.1 Lead diameter wire' -> '05_1 Lead diameter wire'."""
    o = clean_json(o)
    if isinstance(o, dict):
        return {_BAD_KEY.sub("_", str(k)): metadata_safe(v) for k, v in o.items()}
    if isinstance(o, list):
        return [metadata_safe(v) for v in o]
    return o


def source_info(meta: dict) -> dict:
    """Dataset provenance of a pass: {id, title, authors, doi, url, license, synthetic, attribution}."""
    src = meta.get("source")
    if not isinstance(src, dict):
        src = dict(SIM_SOURCE) if meta.get("simulator") or src in (None, "simulator") else {"id": str(src)}
    out = {k: src.get(k) for k in ("id", "title", "authors", "doi", "url", "license") if src.get(k) is not None}
    out["synthetic"] = bool(src.get("synthetic", False))
    if src.get("attribution"):
        out["attribution"] = src["attribution"]
    elif out["synthetic"]:
        out["attribution"] = f"{out.get('title', 'synthetic data')} (synthetic, not a real weld)"
    else:
        bits = [out.get("authors"), out.get("title")]
        att = " — ".join(b for b in bits if b)
        if out.get("doi"):
            att += f". Zenodo, DOI {out['doi']}"
        if out.get("license"):
            att += f". Licensed {out['license']}"
        out["attribution"] = att.strip(". ") + "."
    return out


def ndt_indications(meta: dict) -> list[dict]:
    ndt = meta.get("ndt") if isinstance(meta.get("ndt"), dict) else {}
    return [dict(i) for i in ndt.get("indications") or [] if isinstance(i, dict)]


def flat_keys(meta: dict) -> dict:
    """Derived flat (queryable) keys for the real-data contract."""
    src = source_info(meta)
    ndt = meta.get("ndt") if isinstance(meta.get("ndt"), dict) else {}
    return {"electrodes": int(meta.get("electrodes") or 1), "source_id": src.get("id"),
            "source_license": src.get("license"), "source_doi": src.get("doi"), "synthetic": src["synthetic"],
            "ndt_inspected": bool(ndt.get("inspected", meta.get("rt_result") not in (None, "not_inspected"))),
            "n_indications": len(ndt.get("indications") or []),
            "has_video": bool(meta.get("video")) or bool(meta.get("simulator")),
            "n_photos": len(meta.get("photos") or [])}


def flatten_meta(meta: dict) -> dict:
    """Sequence user-metadata: full meta.json (nested dicts kept) + flat queryable keys."""
    out = dict(meta)
    out["defects"] = [dict(d) for d in meta.get("defects", [])]
    out["n_defects"] = len(out["defects"])
    out.setdefault("has_defect", bool(out["defects"]))
    out.setdefault("defect_types", ",".join(sorted({d["defect"] for d in out["defects"]})) or "none")
    for k, v in flat_keys(meta).items():
        out.setdefault(k, v)
    if not isinstance(out.get("source"), dict):
        out["source"] = source_info(meta)
    return {k: v for k, v in metadata_safe(out).items() if v is not None}


def meta_row(meta: dict) -> dict:
    """Row returned by list_passes (same shape online/offline)."""
    m = {**flat_keys(meta), **{k: v for k, v in meta.items() if v is not None}}
    row = {k: m.get(k) for k in FLAT_KEYS}
    row["defects"] = meta.get("defects", [])
    row["wps"] = meta.get("wps", {})
    row["setpoints"] = meta.get("setpoints", {})
    row["source"] = source_info(meta)
    for k in ("ndt", "photos", "video", "wps_basis"):
        if meta.get(k) is not None:
            row[k] = meta[k]
    return row


# ------------------------------------------------------------------ offline readers


def pass_dir(seq: str) -> Path:
    d = generated_dir() / seq
    if not (d / "meta.json").exists():
        raise FileNotFoundError(f"pass directory not found: {d}")
    return d


@lru_cache(maxsize=256)
def _load_meta_cached(path: str, mtime: float) -> dict:
    return json.loads(Path(path).read_text())


def load_meta(seq_or_dir) -> dict:
    d = Path(seq_or_dir)
    if not (d / "meta.json").exists():
        d = pass_dir(str(seq_or_dir))
    p = d / "meta.json"
    return dict(_load_meta_cached(str(p), p.stat().st_mtime))


def local_sequences() -> list[str]:
    root = generated_dir()
    if not root.exists():
        return []
    return sorted(p.name for p in root.iterdir() if (p / "meta.json").exists())


def movavg(x: np.ndarray, n: int) -> np.ndarray:
    if n <= 1 or len(x) == 0:
        return np.asarray(x, dtype=float)
    k = np.ones(n) / n
    pad = np.pad(np.asarray(x, dtype=float), (n // 2, n - 1 - n // 2), mode="edge")
    return np.convolve(pad, k, mode="valid")


def movmedian(x: np.ndarray, n: int) -> np.ndarray:
    s = pd.Series(np.asarray(x, dtype=float))
    return s.rolling(n, center=True, min_periods=1).median().to_numpy()


def _interp_cols(df: pd.DataFrame) -> pd.DataFrame:
    """Linear interpolation of every column except t_ns; all-NaN columns (gas on SAW) stay NaN."""
    cols = [c for c in df.columns if c != "t_ns"]
    for c in cols:
        x = df[c]
        if x.notna().any() and x.isna().any():
            df[c] = x.interpolate(limit_direction="both")
    return df


def assemble_signals(arc: pd.DataFrame, travel: Optional[pd.DataFrame], thermal: Optional[pd.DataFrame],
                     t0_ns: int, t0_s: Optional[float] = None, t1_s: Optional[float] = None) -> pd.DataFrame:
    """Merge streams onto the ARC_HZ grid: columns t_s + SIGNALS (+ EXTRA_SIGNALS present in the pass).

    travel/thermal are optional (None or empty); core signals a dataset lacks come back as NaN."""
    arc = arc[["t_ns", *[c for c in ARC_COLS if c in arc.columns]]]
    df = arc
    if travel is not None and len(travel):
        travel = travel[["t_ns", *[c for c in TRAVEL_COLS if c in travel.columns]]]
        df = df.merge(travel, on="t_ns", how="outer")
    df = _interp_cols(df.sort_values("t_ns").drop_duplicates("t_ns").reset_index(drop=True))
    tg = df["t_ns"].to_numpy(dtype=float)
    if thermal is not None and len(thermal):
        th_t = thermal["t_ns"].to_numpy(dtype=float)
        for c in THERMAL_COLS:
            if c in thermal.columns:
                x = thermal[c].to_numpy(dtype=float)
                ok = np.isfinite(x)
                df[c] = np.interp(tg, th_t[ok], x[ok]) if ok.sum() >= 1 else np.nan
    df.insert(0, "t_s", (df["t_ns"].to_numpy() - t0_ns) / 1e9)
    df = df.drop(columns=["t_ns"])
    if t0_s is not None:
        df = df[df["t_s"] >= t0_s - 1e-9]
    if t1_s is not None:
        df = df[df["t_s"] < t1_s - 1e-9]
    for c in SIGNALS:
        if c not in df.columns and c not in OPTIONAL_CORE:
            df[c] = np.nan
    cols = ["t_s"] + [c for c in SIGNALS if c in df.columns] + [c for c in EXTRA_SIGNALS if c in df.columns]
    return df[cols].reset_index(drop=True)


def read_optional_parquet(path: Path) -> Optional[pd.DataFrame]:
    return pd.read_parquet(path) if path.exists() else None


def offline_signals(seq: str, t0_s=None, t1_s=None) -> pd.DataFrame:
    d = pass_dir(seq)
    meta = load_meta(d)
    arc = pd.read_parquet(d / "arc.parquet")
    trv = read_optional_parquet(d / "travel.parquet")
    thm = read_optional_parquet(d / "thermal.parquet")
    t0_ns = int(meta.get("t0_ns", arc["t_ns"].iloc[0]))
    return assemble_signals(arc, trv, thm, t0_ns, t0_s, t1_s)


def avg_signals(df: pd.DataFrame) -> pd.DataFrame:
    """0.5 s moving averages (the monitor values used for WPS compliance)."""
    out = df.copy()
    n = ARC_HZ // 2
    for c in AVG_COLS:
        if c in out:
            out[c] = movavg(out[c].to_numpy(), n)
    if "interpass_c" in out:
        out["interpass_c"] = movmedian(out["interpass_c"].to_numpy(), ARC_HZ)
    return out


def json_default(o: Any):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, Path):
        return str(o)
    raise TypeError(type(o))
