#!/usr/bin/env bash
# WeldWorld — one-shot, idempotent RunPod pod setup.
#
# Everything heavy lives on the network volume (/workspace) so a pod restart only needs the
# (fast) apt step again. No docker-in-docker: Postgres, MinIO, mosaicod, pixi and vLLM run natively.
#
#   bash runpod/bootstrap.sh                 # full setup
#   bash runpod/bootstrap.sh --apt-only      # after a pod restart (container disk was wiped)
#   bash runpod/bootstrap.sh --skip-curator --skip-models
#
# Flags / env:
#   --apt-only           only system packages (+ env file), then exit
#   --postgres-only      only (re)initialise + start Postgres (used by start_all.sh after a restart)
#   --skip-apt           skip apt (no root / already installed)
#   --skip-curator       do not install Cosmos Curator (pixi) — curate falls back to BACKEND=lite
#   --force-curator      install Curator even if the driver is older than CUDA 13 (>= 580)
#   --skip-models        do not download Cosmos 3 weights
#   --skip-worldmodels   do not call worldmodels/serve/install.sh
#   --mosaicod-from=X    release | image | source   (default: try in that order)
#   MODELS="nvidia/Cosmos3-Nano ..."    override the HF repos to prefetch into $HF_HOME
#   WITH_SIM_TRANSFER=1  also download nvidia/Cosmos3-Nano-Sim-Transfer (real-time sim2real, ~31 GB)
#   WITH_ANOMALYGEN=1    also download nvidia/Cosmos-AnomalyGen-Metal-Nano (defect LoRA)
#   CURATOR_MODELS=transnetv2,qwen3_8_27b_fp8,cosmos_embed1_336p
#   PYTHON_VERSION=3.12  MINIO_VERSION=latest  MINIO_IMAGE=cgr.dev/chainguard/minio:latest  MOSAICOD_IMAGE=ghcr.io/mosaico-labs/mosaicod:latest
#   MOSAICO_REF=v0.7.0   git tag for the source-build fallback (default: latest release tag, matching PyPI mosaicolabs)
set -Eeuo pipefail

# shellcheck source=runpod/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

APT_ONLY=0; PG_ONLY=0; SKIP_APT=0; SKIP_CURATOR=0; FORCE_CURATOR=0; SKIP_MODELS=0; SKIP_WM=0; MOSAICOD_FROM="auto"
for a in "$@"; do
  case "$a" in
    --apt-only) APT_ONLY=1 ;;
    --postgres-only) PG_ONLY=1 ;;
    --skip-apt) SKIP_APT=1 ;;
    --skip-curator) SKIP_CURATOR=1 ;;
    --force-curator) FORCE_CURATOR=1 ;;
    --skip-models) SKIP_MODELS=1 ;;
    --skip-worldmodels) SKIP_WM=1 ;;
    --mosaicod-from=*) MOSAICOD_FROM="${a#*=}" ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) die "unknown flag: $a" ;;
  esac
done

PYTHON_VERSION="${PYTHON_VERSION:-3.12}"
MINIO_VERSION="${MINIO_VERSION:-latest}"
MOSAICOD_IMAGE="${MOSAICOD_IMAGE:-ghcr.io/mosaico-labs/mosaicod:latest}"
MOSAICO_GIT="${MOSAICO_GIT:-https://github.com/mosaico-labs/mosaico.git}"
CURATOR_GIT="${CURATOR_GIT:-https://github.com/nvidia-cosmos/cosmos-curator.git}"
CURATOR_MODELS="${CURATOR_MODELS:-transnetv2,qwen3_8_27b_fp8,cosmos_embed1_336p}"

mkdir -p "$STATE_DIR" "$LOG_DIR" "$RUN_DIR" "$BIN_DIR" "$MODELS_DIR" "${WS}/.cache" "${WS}/data"
exec > >(tee -a "${LOG_DIR}/bootstrap.log") 2>&1
T0=$(date +%s)
log "WeldWorld bootstrap — repo ${REPO_DIR}, workspace ${WS}"

SUDO=""
if [[ $EUID -ne 0 ]]; then have sudo && SUDO="sudo"; fi

# ================================================================== 0. generated env + secrets
write_env_files() {
  if [[ ! -f "${STATE_DIR}/secrets.env" ]]; then
    umask 077
    local pg mi
    pg="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
    mi="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)"
    cat >"${STATE_DIR}/secrets.env" <<EOF
# generated by runpod/bootstrap.sh on $(date -Is) — keep private
MOSAICOD_DB_PASSWORD=${pg}
MINIO_ROOT_USER=weldworld
MINIO_ROOT_PASSWORD=${mi}
AWS_ACCESS_KEY_ID=weldworld
AWS_SECRET_ACCESS_KEY=${mi}
EOF
    umask 022
    ok "generated ${STATE_DIR}/secrets.env (Postgres + MinIO passwords)"
  fi
  if [[ ! -f "${STATE_DIR}/demo.env" ]]; then
    cp "${REPO_DIR}/configs/demo.env.example" "${STATE_DIR}/demo.env"
    ok "copied configs/demo.env.example -> ${STATE_DIR}/demo.env (edit for HF_TOKEN etc.)"
  fi
  # Paths that must point at the network volume. Regenerated every run. Pure download caches (uv, pixi/rattler,
  # go-build) go to the container disk instead: installed envs on the volume do not need them, and keeping them
  # off the volume lets a 150 GB volume hold everything (they are 30-50 GB).
  local SCRATCH_CACHE="${SCRATCH_CACHE:-/root/.cache/weldworld}"
  mkdir -p "$SCRATCH_CACHE"
  cat >"${STATE_DIR}/env.sh" <<EOF
# generated by runpod/bootstrap.sh — sourced by start_all.sh and ~/.bashrc
WORKSPACE=${WS}
MODELS_DIR=${MODELS_DIR}
LOG_DIR=${LOG_DIR}
DATA_DIR=${REPO_DIR}/data
HF_HOME=${WS}/.cache/huggingface
COSMOS_HOME=${WS}/cosmos
HF_HUB_ENABLE_HF_TRANSFER=0
UV_CACHE_DIR=${SCRATCH_CACHE}/uv
UV_PYTHON_INSTALL_DIR=${WS}/.cache/uv-python
UV_LINK_MODE=copy
PIXI_HOME=${WS}/.pixi
PIXI_CACHE_DIR=${SCRATCH_CACHE}/pixi
RATTLER_CACHE_DIR=${SCRATCH_CACHE}/rattler
GOPATH=${WS}/gopath
GOMODCACHE=${WS}/gopath/pkg/mod
GOCACHE=${SCRATCH_CACHE}/go-build
CARGO_HOME=${WS}/.cargo
RUSTUP_HOME=${WS}/.rustup
PIP_CACHE_DIR=${WS}/.cache/pip
COSMOS_CURATOR_CODE_DIR=${CURATOR_DIR}
COSMOS_CURATOR_LOCAL_WORKSPACE_PREFIX=${WS}
MOSAICOD_DB_URL=postgresql://127.0.0.1:${PG_PORT}/mosaico
MOSAICOD_DB_USER=postgres
MOSAICOD_STORE_ENDPOINT=file://${MOSAICO_STORE_DIR}
MOSAICOD_STORE_BUCKET=mosaico
S3_ENDPOINT=http://localhost:${MINIO_API_PORT}
S3_BUCKET=raw
AWS_DEFAULT_REGION=us-east-1
EOF
  local line="[ -f ${RUNPOD_DIR}/shellrc.sh ] && . ${RUNPOD_DIR}/shellrc.sh"
  grep -qsF "$line" "${HOME}/.bashrc" || echo "$line" >>"${HOME}/.bashrc"
}

# ================================================================== 1. apt
apt_install() {
  hdr "1/9 system packages (apt)"
  local pkgs=(ffmpeg postgresql postgresql-contrib build-essential pkg-config libpq-dev protobuf-compiler
              git git-lfs curl wget ca-certificates jq tmux htop lsof iproute2 unzip zstd xz-utils
              netcat-openbsd rsync python3-venv)
  local missing=() p
  for p in "${pkgs[@]}"; do dpkg -s "$p" >/dev/null 2>&1 || missing+=("$p"); done
  if [[ ${#missing[@]} -eq 0 ]]; then ok "all apt packages present"; return; fi
  log "installing: ${missing[*]}"
  export DEBIAN_FRONTEND=noninteractive
  $SUDO apt-get update -qq
  $SUDO apt-get install -y -qq --no-install-recommends "${missing[@]}"
  git lfs install --skip-repo >/dev/null 2>&1 || true
  ok "apt packages installed"
}

# ================================================================== 2. uv + repo venv
install_uv() {
  hdr "2/9 uv + repo virtualenv"
  if [[ ! -x "${BIN_DIR}/uv" ]]; then
    curl -LsSf https://astral.sh/uv/install.sh | env UV_INSTALL_DIR="${BIN_DIR}" UV_NO_MODIFY_PATH=1 sh
  fi
  ok "uv $("${BIN_DIR}/uv" --version | awk '{print $2}')"
  if [[ ! -x "${VENV_DIR}/bin/python" ]]; then
    "${BIN_DIR}/uv" venv --python "${PYTHON_VERSION}" "${VENV_DIR}"
  fi
  "${BIN_DIR}/uv" pip install --python "${VENV_DIR}/bin/python" -q -r "${REPO_DIR}/requirements.txt"
  if [[ -f "${REPO_DIR}/pyproject.toml" ]]; then
    "${BIN_DIR}/uv" pip install --python "${VENV_DIR}/bin/python" -q -e "${REPO_DIR}" || warn "editable install failed (ok: scripts run from repo root)"
  fi
  ok "repo venv ${VENV_DIR} ($("${VENV_DIR}/bin/python" --version))"
}

# ================================================================== 3. Postgres
init_postgres() {
  hdr "3/9 PostgreSQL"
  local pgbin; pgbin="$(find /usr/lib/postgresql -mindepth 2 -maxdepth 2 -type d -name bin 2>/dev/null | sort -V | tail -1)"
  [[ -n "$pgbin" ]] || die "postgresql binaries not found (apt step skipped?)"
  local pgdata="${WELDWORLD_PGDATA:-$PGDATA_DEFAULT}"   # ignore stale PGDATA from an older pg.env
  if [[ ! -s "${pgdata}/PG_VERSION" ]]; then
    # a brand-new (empty) catalog: drop Mosaico files left by an earlier pod so catalog and store match
    rm -rf "${MOSAICO_STORE_DIR:?}"/* 2>/dev/null || true
    mkdir -p "$pgdata"; chown -R postgres:postgres "$pgdata"; chmod 700 "$pgdata"
    su postgres -c "${pgbin}/initdb -D '${pgdata}' -U postgres --auth-local=trust --auth-host=scram-sha-256 -E UTF8" >/dev/null \
      || die "initdb ${pgdata} failed"
    {
      echo "listen_addresses = 'localhost'"
      echo "port = ${PG_PORT}"
      echo "unix_socket_directories = '/tmp'"
    } >>"${pgdata}/postgresql.conf"
    ok "initdb ${pgdata}"
  fi
  echo "PGDATA=${pgdata}" >"${STATE_DIR}/pg.env"
  echo "PGBIN=${pgbin}" >>"${STATE_DIR}/pg.env"
  if ! su postgres -c "${pgbin}/pg_ctl -D '${pgdata}' status" >/dev/null 2>&1; then
    pg_log_prepare
    su postgres -c "${pgbin}/pg_ctl -D '${pgdata}' -l '${PG_LOG}' -w start" >/dev/null || { tail -n 20 "$PG_LOG" >&2; die "postgres did not start"; }
  fi
  # shellcheck disable=SC1091
  . "${STATE_DIR}/secrets.env"
  su postgres -c "psql -h /tmp -p ${PG_PORT} -qtAc \"ALTER USER postgres PASSWORD '${MOSAICOD_DB_PASSWORD}'\"" >/dev/null
  if ! su postgres -c "psql -h /tmp -p ${PG_PORT} -qtAc \"SELECT 1 FROM pg_database WHERE datname='mosaico'\"" | grep -q 1; then
    su postgres -c "createdb -h /tmp -p ${PG_PORT} mosaico"
    ok "created database mosaico"
  fi
  ok "postgres running (${pgdata}), db mosaico ready"
}

# ================================================================== 4. crane (OCI image export tool)
install_crane() {
  if [[ -x "${BIN_DIR}/crane" ]]; then return 0; fi
  local tmp; tmp="$(mktemp -d)"
  curl -fsSL -o "${tmp}/gcr.tgz" \
    "https://github.com/google/go-containerregistry/releases/latest/download/go-containerregistry_Linux_x86_64.tar.gz"
  tar -xzf "${tmp}/gcr.tgz" -C "${tmp}" crane
  install -m 755 "${tmp}/crane" "${BIN_DIR}/crane"
  rm -rf "$tmp"
  ok "crane installed"
}

# ================================================================== 5. MinIO (source-only since late 2025)
install_go() {
  if [[ -x "${WS}/go/bin/go" ]]; then return 0; fi
  local v; v="$(curl -fsSL 'https://go.dev/VERSION?m=text' | head -1)"
  log "installing ${v} to ${WS}/go (needed to build MinIO from source)"
  curl -fsSL "https://go.dev/dl/${v}.linux-amd64.tar.gz" | tar -xz -C "${WS}"
}

# Fast path: lift the (static Go) binary out of a maintained MinIO image, the same image
# infra/docker-compose.yml uses. Only kept if it actually runs here.
minio_from_image() {
  install_crane || return 1
  local tmp img="${MINIO_IMAGE:-cgr.dev/chainguard/minio:latest}"; tmp="$(mktemp -d)"
  if "${BIN_DIR}/crane" export --platform linux/amd64 "$img" - | tar -xf - -C "$tmp" usr/bin/minio 2>/dev/null \
     && "${tmp}/usr/bin/minio" --version >/dev/null 2>&1; then
    install -m 755 "${tmp}/usr/bin/minio" "${BIN_DIR}/minio"; ok "minio extracted from ${img}"
  else
    warn "could not use the minio binary from ${img} — building from source"
  fi
  rm -rf "$tmp"
}

install_minio() {
  hdr "4/9 MinIO (S3 for Cosmos Curator video-cut)"
  if [[ ! -x "${BIN_DIR}/minio" ]]; then minio_from_image || true; fi
  if [[ -x "${BIN_DIR}/minio" ]]; then ok "minio present"; else
    # MinIO community edition stopped publishing binaries/images (dl.min.io returns 410);
    # the documented path is `go install github.com/minio/minio@latest`.
    install_go
    log "go install github.com/minio/minio@${MINIO_VERSION} (takes a few minutes)"
    if GOBIN="${BIN_DIR}" "${WS}/go/bin/go" install "github.com/minio/minio@${MINIO_VERSION}"; then
      ok "minio built from source"
    else
      warn "MinIO build failed — Curator Next (S3 input) will be unavailable; BACKEND=lite still works"
      return 0
    fi
  fi
  mkdir -p "${MINIO_DATA}"
}

create_bucket() {
  # needs minio running (start_all.sh starts it); bucket creation via boto3 from the repo venv
  S3_ENDPOINT="http://localhost:${MINIO_API_PORT}" "${VENV_DIR}/bin/python" - <<'PY' || warn "bucket creation failed (is MinIO running?)"
import os, boto3, botocore
s3 = boto3.client("s3", endpoint_url=os.environ.get("S3_ENDPOINT", "http://localhost:9000"),
                  aws_access_key_id=os.environ["AWS_ACCESS_KEY_ID"],
                  aws_secret_access_key=os.environ["AWS_SECRET_ACCESS_KEY"], region_name="us-east-1")
