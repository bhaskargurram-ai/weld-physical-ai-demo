# ================================================================== 6. mosaicod
mosaicod_from_release() {
  local tmp; tmp="$(mktemp -d)"
  local base="https://github.com/mosaico-labs/mosaico/releases/latest/download"
  curl -fsSL -o "${tmp}/m.tgz" "${base}/mosaicod-linux-amd64.tar.gz" || { rm -rf "$tmp"; return 1; }
  if curl -fsSL -o "${tmp}/m.tgz.sha256" "${base}/mosaicod-linux-amd64.tar.gz.sha256"; then
    (cd "$tmp" && sed 's#  .*#  m.tgz#' m.tgz.sha256 | sha256sum -c --quiet -) || { rm -rf "$tmp"; return 1; }
  fi
  tar -xzf "${tmp}/m.tgz" -C "$tmp" mosaicod && install -m 755 "${tmp}/mosaicod" "${BIN_DIR}/mosaicod"
  rm -rf "$tmp"
}

mosaicod_from_image() {
  install_crane
  local tmp; tmp="$(mktemp -d)"
  # distroless image: binary at /usr/local/bin/mosaicod (docker/dockerfiles/Dockerfile.mosaicod)
  "${BIN_DIR}/crane" export --platform linux/amd64 "${MOSAICOD_IMAGE}" - \
    | tar -xf - -C "$tmp" usr/local/bin/mosaicod || { rm -rf "$tmp"; return 1; }
  install -m 755 "${tmp}/usr/local/bin/mosaicod" "${BIN_DIR}/mosaicod"
  rm -rf "$tmp"
}

mosaicod_from_source() {
  if ! have cargo; then
    curl -fsSL https://sh.rustup.rs | sh -s -- -y --profile minimal --default-toolchain 1.92 --no-modify-path
  fi
  local src="${WS}/src/mosaico" ref="${MOSAICO_REF:-}"
  # Build the latest *release* tag by default: `main` can be ahead of the mosaicolabs SDK on PyPI.
  if [[ -z "$ref" ]]; then
    ref="$(git ls-remote --tags --refs "$MOSAICO_GIT" 'v*' | awk -F/ '{print $NF}' | sort -V | tail -1)"
  fi
  rm -rf "$src"
  git clone --depth 1 ${ref:+--branch "$ref"} "$MOSAICO_GIT" "$src"
  # build.rs compiles ../../../proto with protox (pure Rust, no protoc); sqlx uses cached .sqlx queries
  (cd "${src}/mosaicod" && SQLX_OFFLINE=true cargo build --release --bin mosaicod)
  install -m 755 "${src}/mosaicod/target/release/mosaicod" "${BIN_DIR}/mosaicod"
}

install_mosaicod() {
  hdr "5/9 mosaicod"
  if [[ -x "${BIN_DIR}/mosaicod" ]] && "${BIN_DIR}/mosaicod" --version >/dev/null 2>&1; then
    ok "mosaicod present ($("${BIN_DIR}/mosaicod" --version 2>/dev/null | head -1))"; return
  fi
  local order
  case "$MOSAICOD_FROM" in
    auto) order=(release image source) ;;
    *) order=("$MOSAICOD_FROM") ;;
  esac
  local m
  for m in "${order[@]}"; do
    log "mosaicod: trying ${m}"
    if "mosaicod_from_${m}"; then ok "mosaicod installed from ${m}"; break; fi
    warn "mosaicod from ${m} failed"
  done
  [[ -x "${BIN_DIR}/mosaicod" ]] || die "could not install mosaicod"
  mkdir -p "${MOSAICO_STORE_DIR}"
}

# ================================================================== 7. Cosmos Curator (pixi)
install_curator() {
  hdr "6/9 Cosmos Curator (pixi, CUDA 13)"
  local drv; drv="$(driver_major)"
  if [[ $SKIP_CURATOR -eq 1 ]]; then warn "skipped (--skip-curator) -> use CURATE_BACKEND=lite"; return; fi
  if [[ "${drv:-0}" -lt 580 && $FORCE_CURATOR -eq 0 ]]; then
    warn "driver ${drv:-none} < 580: Curator's pixi env needs CUDA 13. Skipping -> CURATE_BACKEND=lite."
    warn "Redeploy with 'runpodctl pod create --min-cuda-version 13.0' (or the CUDA filter in the console) to use Curator."
    echo "CURATE_BACKEND=lite" >"${STATE_DIR}/curator.env"
    return
  fi
  if ! [[ -x "${WS}/.pixi/bin/pixi" ]]; then
    curl -fsSL https://pixi.sh/install.sh | env PIXI_HOME="${WS}/.pixi" PIXI_NO_PATH_UPDATE=1 bash
  fi
  if [[ -d "${CURATOR_DIR}/.git" ]]; then
    git -C "$CURATOR_DIR" pull --ff-only -q || warn "curator: git pull failed (keeping current checkout)"
    git -C "$CURATOR_DIR" submodule update --init --recursive -q
  else
    git clone --recurse-submodules "$CURATOR_GIT" "$CURATOR_DIR"
  fi
  local extra=()
  [[ "${drv:-0}" -lt 580 ]] && extra=(env CONDA_OVERRIDE_CUDA=13.0)
  (cd "$CURATOR_DIR" && "${extra[@]}" "${WS}/.pixi/bin/pixi" install --frozen -e default)
  ok "pixi env 'default' installed"

  # HF credentials for model-download (Curator reads ~/.config/cosmos_curator/config.yaml)
  mkdir -p "${STATE_DIR}/cosmos_curator" "${HOME}/.config"
  umask 077
  cat >"${STATE_DIR}/cosmos_curator/config.yaml" <<EOF
huggingface:
    user: "${HF_USER:-weldworld}"
    api_key: "${HF_TOKEN:-}"
EOF
  umask 022
  ln -sfn "${STATE_DIR}/cosmos_curator" "${HOME}/.config/cosmos_curator"
  # ...but Curator's own loader (model-download, pipelines) only reads the in-container path
  # /cosmos_curator/config/cosmos_curator.yaml (cosmos_curator/core/utils/environment.py)
  mkdir -p /cosmos_curator/config
  ln -sfn "${STATE_DIR}/cosmos_curator/config.yaml" /cosmos_curator/config/cosmos_curator.yaml
  # Curator resolves weights at /config/models/<model_id> (CONTAINER_PATHS_DEFAULT_WORKSPACE_DIR)
  mkdir -p "${CURATOR_WS}/models"
  if [[ ! -e /config || -L /config ]]; then ln -sfn "${CURATOR_WS}" /config; else warn "/config exists and is not a symlink"; fi
  printf 'CURATE_BACKEND=curator-next\nCURATOR_HOME=%s\n' "$CURATOR_DIR" >"${STATE_DIR}/curator.env"

  if [[ $SKIP_MODELS -eq 0 ]]; then
    log "curator model-download: ${CURATOR_MODELS}"
    (cd "$CURATOR_DIR" && COSMOS_CURATOR_CODE_DIR="$CURATOR_DIR" "${WS}/.pixi/bin/pixi" run -e default --as-is \
        model-download --models "${CURATOR_MODELS}") || warn "curator model-download failed (check HF_TOKEN)"
  fi
}

# ================================================================== 8. Cosmos 3 weights
download_models() {
  hdr "7/9 Cosmos 3 weights -> HF cache ${HF_HOME}"
  if [[ $SKIP_MODELS -eq 1 ]]; then warn "skipped (--skip-models)"; return; fi
  # Same cache the serve scripts use (vLLM loads nvidia/Cosmos3-Nano by repo id), so
  # worldmodels/serve/install.sh's own prefetch becomes a no-op. One omnimodal checkpoint
  # (~34 GB) serves Reasoner, Generator and Transfer. 1-GPU pods quantise online (fp8).
  local repos r hf="${VENV_DIR}/bin/hf"
  if [[ -n "${MODELS:-}" ]]; then read -r -a repos <<<"${MODELS}"; else repos=(nvidia/Cosmos3-Nano); fi
  [[ "${WITH_SIM_TRANSFER:-0}" == 1 ]] && repos+=(nvidia/Cosmos3-Nano-Sim-Transfer)
  [[ "${WITH_ANOMALYGEN:-0}" == 1 ]] && repos+=(nvidia/Cosmos-AnomalyGen-Metal-Nano)
  [[ -x "$hf" ]] || die "hf CLI missing in ${VENV_DIR} (huggingface_hub not installed?)"
  for r in "${repos[@]}"; do
    log "hf download ${r}"
    HF_HOME="$HF_HOME" "$hf" download "$r" >/dev/null   # resumable; reads HF_TOKEN from env
    ok "${r} cached"
  done
  du -sh "${HF_HOME}/hub" 2>/dev/null | awk '{print "  HF cache: " $1}'
}

# ================================================================== 9. world-model servers (agent C)
install_worldmodels() {
  hdr "8/9 Cosmos 3 serving stack (worldmodels/serve/install.sh)"
  if [[ $SKIP_WM -eq 1 ]]; then warn "skipped (--skip-worldmodels)"; return; fi
  local inst="${REPO_DIR}/worldmodels/serve/install.sh"
  if [[ ! -f "$inst" ]]; then warn "worldmodels/serve/install.sh not found — skipping"; return; fi
  if [[ "$(gpu_count)" -eq 0 ]]; then warn "no GPU — skipping (use COSMOS_BACKEND=replay or nim)"; return; fi
  # Reasoner and Generator install separately: one failing must not take the other (or the run) down.
  local part ok_parts=()
  for part in REASONER GENERATOR; do
    local want_r=0 want_g=0
    [[ $part == REASONER ]] && want_r=1
    [[ $part == GENERATOR ]] && want_g=1
    if env COSMOS_CUDA_TAG="$(cuda_flavor)" COSMOS_HOME="${COSMOS_HOME:-${WS}/cosmos}" HF_HOME="$HF_HOME" \
        INSTALL_REASONER="$want_r" INSTALL_GENERATOR="$want_g" \
        PREFETCH_WEIGHTS=0 INSTALL_ANOMALYGEN="${WITH_ANOMALYGEN:-0}" bash "$inst"; then
      ok_parts+=("$part")
    else
      warn "Cosmos 3 ${part,,} install failed — the copilot uses cache/nim/replay for it (see log above)"
    fi
  done
  ok "worldmodels serving stack: ${ok_parts[*]:-none} installed (CUDA_FLAVOR=$(cuda_flavor))"
}

# Container-disk links that a pod restart wipes (targets live on /workspace).
restore_links() {
  if [[ -f "${STATE_DIR}/aws/credentials" ]]; then
    mkdir -p "${HOME}/.aws"; ln -sfn "${STATE_DIR}/aws/credentials" "${HOME}/.aws/credentials"
  fi
  if [[ -d "${STATE_DIR}/cosmos_curator" ]]; then
    mkdir -p "${HOME}/.config"; ln -sfn "${STATE_DIR}/cosmos_curator" "${HOME}/.config/cosmos_curator"
  fi
  if [[ -d "${CURATOR_WS}" && ( ! -e /config || -L /config ) ]]; then ln -sfn "${CURATOR_WS}" /config; fi
  if [[ -f "${STATE_DIR}/cosmos_curator/config.yaml" ]]; then
    mkdir -p /cosmos_curator/config
