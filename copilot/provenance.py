def source_of(meta: dict | None) -> dict:
    """Normalised source record for a pass: registry entry overlaid with what meta.json says."""
    src = (meta or {}).get("source")
    if isinstance(src, dict):
        sid = src.get("id") or ""
        base = dict(DATASETS.get(sid) or (SIMULATOR if src.get("synthetic") else {}))
        base.update({k: v for k, v in src.items() if v not in (None, "", [])})
        base.setdefault("id", sid or "unknown")
        base.setdefault("short", base.get("title") or base["id"])
        base["synthetic"] = bool(src.get("synthetic", base.get("synthetic", False)))
        if base["synthetic"]:
            base.setdefault("pass_word", "P")
        return base
    return dict(SIMULATOR)


def attribution(src: dict) -> str:
    """One-line TASL attribution (Title, Author, Source, License) + modifications."""
    if src.get("synthetic"):
        return "Synthetic data generated by the WeldCell simulator (not real welds)."
    parts = [(src.get("authors") or "").rstrip("."), f"“{src.get('title')}”", "Zenodo",
             f"https://doi.org/{src['doi']}" if src.get("doi") else src.get("url"), src.get("license")]
    line = ". ".join(p for p in parts if p) + "."
    if src.get("modified"):
        line += " " + src["modified"]
    return line


def public(src: dict) -> dict:
    keys = ("id", "short", "org", "title", "project", "authors", "doi", "url", "license", "license_url",
            "synthetic", "process", "material", "streams", "modified", "photo_caption", "video_caption", "pass_word")
    out = {k: src.get(k) for k in keys if src.get(k) not in (None, "")}
    out["synthetic"] = bool(src.get("synthetic"))
    out["attribution"] = attribution(src)
    return out
